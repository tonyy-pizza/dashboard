"""Every file the dashboard reads or writes, in one place.

The scripts live in PROJECT_DIR; everything they generate goes into one of
four subfolders beside them, so the project root stays just code:

    dashboard-project-files\\
        *.py                    the scripts
        fonts\\                  Inter + Fraunces (optional)
        cache\\                  cache.json, calendar_sync_status.json
        data\\                   todo.json, habits.json, rough_notes.txt
        secrets\\                calendar_url.txt, OAuth credentials + tokens
        logs\\                   calendar_sync.log, dashboard_crash.log

`.git`, `.gitignore` and `__pycache__` have to stay where they are — git and
Python decide those, not us.

PROJECT_DIR can be pointed somewhere else with DASHBOARD_DATA_DIR (and the
Doom notes with DASHBOARD_NOTES_DIR), which is how the stores get exercised on
a non-Windows machine and in the tests.
"""

