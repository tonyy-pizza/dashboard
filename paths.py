COLLECTOR_SCRIPT = PROJECT_DIR / "collector.py"

# Everything an older, flat layout left in the project root, and where each
# one belongs now.
LEGACY_LAYOUT = {
    "cache.json": CACHE_PATH,
    "calendar_sync_status.json": SYNC_STATUS_PATH,
    "todo.json": TODO_PATH,
    "habits.json": HABITS_PATH,
    "rough_notes.txt": ROUGH_NOTES_PATH,
    "calendar_url.txt": ICAL_URL_PATH,
    "gcal_sync_credentials.json": GOOGLE_SYNC_CREDENTIALS_PATH,
    "gcal_sync_token.json": GOOGLE_SYNC_TOKEN_PATH,
    "graph_app.json": GRAPH_APP_PATH,
    "graph_token_cache.json": GRAPH_TOKEN_CACHE_PATH,
    "calendar_sync.log": SYNC_LOG_PATH,
    "dashboard_crash.log": CRASH_LOG_PATH,
    # Left behind by an atomic write that was interrupted.
    "credentials.json": SECRETS_DIR / "credentials.json",
    "token.json": SECRETS_DIR / "token.json",
}


# A write creates its scratch file and renames it over the target within
# milliseconds. One still sitting here an hour later belongs to a run that
# was killed — the collector hitting the widget's 300s timeout, the machine
# sleeping mid-write, a reboot.
TEMP_SWEEP_AGE_SECONDS = 3600


def ensure_dirs() -> None:
    for directory in MANAGED_DIRS:
        directory.mkdir(parents=True, exist_ok=True)


def sweep_temp_files(older_than_seconds=TEMP_SWEEP_AGE_SECONDS) -> list:
    """Delete orphaned atomic-write scratch files.

    Only ones old enough that no live write could still own them, so this is
    safe to run while the dashboard and the sync are going.
    """
    cutoff = time.time() - older_than_seconds
    removed = []
    for directory in (PROJECT_DIR,) + MANAGED_DIRS:
        if not directory.is_dir():
            continue
        for leftover in directory.glob("*.tmp"):
            try:
                if leftover.is_file() and leftover.stat().st_mtime < cutoff:
                    leftover.unlink()
                    removed.append(leftover)
            except OSError:
                continue        # locked or already gone
    return removed


def migrate_legacy_files() -> list:
    """Move files an older flat layout left in the project root.

    Only ever moves a file when its new home is empty, so it can't overwrite
    newer data and it's safe to call on every run.
    """
    moved = []
    for name, destination in LEGACY_LAYOUT.items():
        source = PROJECT_DIR / name
        if source.resolve() == destination.resolve():
            continue                      # already where it belongs
        if not source.is_file() or destination.exists():
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.move(str(source), str(destination))
        except OSError:
            continue                      # locked or unreadable; leave it
        moved.append((name, destination))
    return moved


def prepare() -> list:
    """Create the folders, rehome anything from the old layout, and clear out
    orphaned scratch files. Every entry point calls this before touching a
    file. Returns the moves, which are worth reporting; the swept temp files
    are garbage by definition and go quietly."""
    ensure_dirs()
    moved = migrate_legacy_files()
    sweep_temp_files()
    return moved
